#!/usr/bin/env python3
"""Turns the pixel font (tools/pixel_font.py) into src/ui/fonts.rs: 4 bits of coverage per pixel, each glyph cropped
to its ink. Also the SMOOTH set (the FONT setting): Barlow Semi Condensed Bold (tools/fonts/, SIL Open Font License
1.1, copyright 2017 The Barlow Project Authors, https://github.com/jpt/barlow; TTF and licence from
https://github.com/google/fonts/tree/main/ofl/barlowsemicondensed) anti-aliased by PIL into the pixel font's own
cell at each scale 2 to 8 (the advance and height of the pixel font times the scale, the ink at most 5 cells wide
times the scale so the layouts that leave a blank column stay true, drawn 1:1). Glyphs the font lacks (the cue
arrows) have advance 0 and are drawn with the pixel font. The output is committed, so a build needs neither this
script nor PIL. Run it again after changing a font:

    python3 tools/font.py
"""
import subprocess, sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
FIRST, LAST = 0x20, 0x7e     # printable ASCII; anything else is drawn as '?'

# (Rust name, what it is for, glyphs): PIXEL is this project's own (tools/pixel_font.py); SMOOTH<n> are the FONT
# setting's, one for each scale n the UI draws at.
def fonts():
    yield 'PIXEL', 'the UI: 5 x 7 dot matrix, drawn scaled like Ferris', pixel_glyphs()
    for n in SMOOTH_SCALES:
        yield f'SMOOTH{n}', f'the UI at scale {n} in Barlow Semi Condensed Bold (SMOOTH setting), drawn 1:1', smooth_glyphs(n)


def pixel_glyphs():
    """The glyphs of the pixel font: coverage is 0 or 15. Returns (line height, baseline, glyph cells)."""
    from pixel_font import GLYPHS, ADVANCE, HEIGHT, BASELINE, EXTRA
    out = []
    for code in [*range(FIRST, LAST + 1), *map(ord, EXTRA)]:
        rows = GLYPHS[chr(code)].split()
        assert all(len(r) == 5 for r in rows) and len(rows) in (7, 8, 9), repr(chr(code))
        img = Image.new('L', (ADVANCE, HEIGHT), 0)
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == '#':
                    img.putpixel((x, y), 255)
        out.append(cell(code, ADVANCE, img))
    return HEIGHT, BASELINE, out


SMOOTH_TTF = Path(__file__).resolve().parent / 'fonts' / 'BarlowSemiCondensed-Bold.ttf'
SMOOTH_EM = 9.5    # px per em for each unit of scale: the ascenders then fill the 7 rows above the baseline
SMOOTH_SCALES = range(2, 9)
# from scale 5 only what a value shows (digits, capitals, punctuation): lower case would add 250 KB
BIG_SCALE, BIG_CHARS = 5, "0123456789.:-+/%' ABCDEFGHIJKLMNOPQRSTUVWXYZ"


def smooth_glyphs(scale):
    """The smooth glyphs for one scale: cells of 6s x 10s px, the baseline 7s from the top (the pixel font's), the
    tallest ascender 7s tall, ink centred in the first 5s columns and squeezed to fit them."""
    from PIL import ImageDraw, ImageFont
    from pixel_font import ADVANCE, HEIGHT, BASELINE, EXTRA
    font = ImageFont.truetype(str(SMOOTH_TTF), SMOOTH_EM * scale)
    w, h, ink_w, base = ADVANCE * scale, HEIGHT * scale, 5 * scale, BASELINE * scale
    out = []
    for code in [*range(FIRST, LAST + 1), *map(ord, EXTRA)]:
        if not FIRST <= code <= LAST or (scale >= BIG_SCALE and chr(code) not in BIG_CHARS):
            out.append((code, 0, 0, 0, 0, 0, []))    # advance 0: not in this font, the pixel font draws it
            continue
        big = Image.new('L', (4 * w, 3 * h), 0)      # room all round; the baseline at 'h' down
        ImageDraw.Draw(big).text((w, h), chr(code), 255, font=font, anchor='ls')
        box = big.getbbox()
        img = Image.new('L', (w, h), 0)
        if box:
            glyph = big.crop(box)
            if glyph.width > ink_w:
                glyph = glyph.resize((ink_w, glyph.height), Image.LANCZOS)
            x, y = (ink_w - glyph.width) // 2, box[1] - h + base
            # a tall '$' or a '(' may poke out by a pixel or two: paste clips it to the cell
            assert -scale <= y and y + glyph.height <= h + scale, f'{chr(code)!r} at scale {scale}: {y}'
            img.paste(glyph, (x, y))
        out.append(cell(code, w, img))
    return h, base, out


def cell(code, advance, img):
    """One glyph cell image cropped to its ink: (code, advance, x, y, w, h, coverage 0..15 row by row)."""
    x0, y0, x1, y1 = img.getbbox() or (0, 0, 0, 0)
    px = [(img.getpixel((x, y)) * 15 + 127) // 255 for y in range(y0, y1) for x in range(x0, x1)]
    return (code, advance, x0, y0, x1 - x0, y1 - y0, px)


def main():
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    lines = ['//! Generated by tools/font.py: do not edit. PIXEL is this project\'s own, drawn in tools/pixel_font.py; SMOOTH2 to',
             '//! SMOOTH8 are Barlow Semi Condensed Bold (SIL OFL 1.1, copyright 2017 The Barlow Project Authors,',
             '//! <https://github.com/jpt/barlow>, licence in tools/fonts/OFL.txt) rasterized into the same cells.',
             '',
             'use crate::text::{Font, Glyph};',
             '']
    total = 0
    for name, what, (height, ascent, gs) in fonts():
        data, table = bytearray(), []
        for code, advance, x, y, w, h, px in gs:
            at = len(data)
            px = px + [0] * (len(px) % 2)
            data += bytes(px[i] << 4 | px[i + 1] for i in range(0, len(px), 2))
            glyph = f'Glyph {{ advance: {advance}, x: {x}, y: {y}, w: {w}, h: {h}, at: {at} }}'
            table.append(f'    {glyph}, // {chr(code)!r}')
        total += len(data) + 8 * len(gs)
        lines += [f'/// Font for {what}: {height} px per line, baseline {ascent} px from the top.',
                  f'pub static {name}: Font =',
                  f'    Font {{ height: {height}, glyphs: &{name}_GLYPHS, alpha: &{name}_ALPHA }};',
                  '',
                  f'static {name}_GLYPHS: [Glyph; {len(gs)}] = [',
                  *table,
                  '];',
                  '',
                  f'static {name}_ALPHA: [u8; {len(data)}] = [']
        for i in range(0, len(data), 24):
            lines.append('    ' + ' '.join(f'0x{b:02x},' for b in data[i:i + 24]))
        lines += ['];', '']
    lines += ['/// The smooth font for text the pixel font draws at `scale` (the same cell, drawn 1:1), if there is one: scale 1',
              '/// stays the pixel font.',
              'pub fn smooth(scale: u32) -> Option<&\'static Font> {',
              '    match scale {',
              *[f'        {n} => Some(&SMOOTH{n}),' for n in SMOOTH_SCALES],
              '        _ => None,',
              '    }',
              '}', '']
    out = ROOT / 'src' / 'ui' / 'fonts.rs'
    out.write_text('\n'.join(lines))
    subprocess.run(['rustfmt', '--edition', '2024', '--config-path', str(ROOT / 'rustfmt.toml'), str(out)], check=True)
    print(f'src/ui/fonts.rs: {1 + len(SMOOTH_SCALES)} fonts, about {total} B in the image')


if __name__ == '__main__':
    sys.exit(main())
