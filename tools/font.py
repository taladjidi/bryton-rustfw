#!/usr/bin/env python3
"""Turns the pixel font (tools/pixel_font.py) into src/ui/fonts.rs: 4 bits of coverage per pixel, each glyph cropped
to its ink. The output is committed, so a build needs neither this script nor PIL. Run it again after changing the
pixel font:

    python3 tools/font.py
"""
import subprocess, sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
FIRST, LAST = 0x20, 0x7e     # printable ASCII; anything else is drawn as '?'

# (Rust name, what it is for): the pixel font is the only one; its glyphs come from tools/pixel_font.py.
FONTS = [
    ('PIXEL', 'the UI: 5 x 7 dot matrix, drawn scaled like Ferris'),
]


def pixel_glyphs():
    """The glyphs of the pixel font: coverage is 0 or 15. Returns (line height, baseline, glyph cells)."""
    from pixel_font import GLYPHS, ADVANCE, HEIGHT, BASELINE, EXTRA
    out = []
    for code in [*range(FIRST, LAST + 1), *map(ord, EXTRA)]:
        rows = GLYPHS[chr(code)].split()
        assert all(len(r) == 5 for r in rows) and len(rows) in (7, 8, 9), repr(chr(code))
        img = Image.new('L', (ADVANCE, HEIGHT), 0)
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == '#':
                    img.putpixel((x, y), 255)
        out.append(cell(code, ADVANCE, img))
    return HEIGHT, BASELINE, out


def cell(code, advance, img):
    """One glyph cell image cropped to its ink: (code, advance, x, y, w, h, coverage 0..15 row by row)."""
    x0, y0, x1, y1 = img.getbbox() or (0, 0, 0, 0)
    px = [(img.getpixel((x, y)) * 15 + 127) // 255 for y in range(y0, y1) for x in range(x0, x1)]
    return (code, advance, x0, y0, x1 - x0, y1 - y0, px)


def main():
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    lines = ['//! Generated by tools/font.py: do not edit. PIXEL is this project\'s own, drawn in tools/pixel_font.py.',
             '',
             'use crate::text::{Font, Glyph};',
             '']
    total = 0
    for name, what in FONTS:
        height, ascent, gs = pixel_glyphs()
        data, table = bytearray(), []
        for code, advance, x, y, w, h, px in gs:
            at = len(data)
            px = px + [0] * (len(px) % 2)
            data += bytes(px[i] << 4 | px[i + 1] for i in range(0, len(px), 2))
            glyph = f'Glyph {{ advance: {advance}, x: {x}, y: {y}, w: {w}, h: {h}, at: {at} }}'
            table.append(f'    {glyph}, // {chr(code)!r}')
        total += len(data) + 8 * len(gs)
        lines += [f'/// Pixel font (tools/pixel_font.py), for {what}: {height} px per line, baseline {ascent} px from the top.',
                  f'pub static {name}: Font =',
                  f'    Font {{ height: {height}, glyphs: &{name}_GLYPHS, alpha: &{name}_ALPHA }};',
                  '',
                  f'static {name}_GLYPHS: [Glyph; {len(gs)}] = [',
                  *table,
                  '];',
                  '',
                  f'static {name}_ALPHA: [u8; {len(data)}] = [']
        for i in range(0, len(data), 24):
            lines.append('    ' + ' '.join(f'0x{b:02x},' for b in data[i:i + 24]))
        lines += ['];', '']
    out = ROOT / 'src' / 'ui' / 'fonts.rs'
    out.write_text('\n'.join(lines))
    subprocess.run(['rustfmt', '--edition', '2024', '--config-path', str(ROOT / 'rustfmt.toml'), str(out)], check=True)
    print(f'src/ui/fonts.rs: {len(FONTS)} font, about {total} B in the image')


if __name__ == '__main__':
    sys.exit(main())
