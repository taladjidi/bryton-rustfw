#!/usr/bin/env python3
"""Rasterizes TrueType fonts into src/fonts.rs: anti-aliased glyphs, 4 bits of coverage per pixel, cropped to
their ink. The output is committed, so a build needs neither this script nor PIL. Run it again after changing
FONTS (adding a font or a size is one line there):

    python3 tools/font.py

The font is DejaVu Sans (Bitstream Vera licence: derivatives allowed, see the header written into fonts.rs),
taken from matplotlib's copy unless DEJAVU points at a directory holding DejaVuSans.ttf and DejaVuSans-Bold.ttf.
"""
import os, subprocess, sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FIRST, LAST = 0x20, 0x7e     # printable ASCII; anything else is drawn as '?'

# (Rust name, file, pixel size, what it is for); file 'pixel' is the hand-drawn tools/pixel_font.py (no size).
FONTS = [
    ('PIXEL', 'pixel', None, 'the UI: 5 x 7 dot matrix, drawn scaled like Ferris'),
    ('SANS_16', 'DejaVuSans.ttf', 16, 'labels and small text'),
    ('SANS_BOLD_32', 'DejaVuSans-Bold.ttf', 32, 'values'),
]


def pixel_glyphs():
    """The same as glyphs(), for the pixel font: coverage is 0 or 15."""
    from pixel_font import GLYPHS, ADVANCE, HEIGHT, BASELINE
    out = []
    for code in range(FIRST, LAST + 1):
        rows = GLYPHS[chr(code)].split()
        assert all(len(r) == 5 for r in rows) and len(rows) in (7, 8, 9), repr(chr(code))
        img = Image.new('L', (ADVANCE, HEIGHT), 0)
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == '#':
                    img.putpixel((x, y), 255)
        out.append(cell(code, ADVANCE, img))
    return HEIGHT, BASELINE, out


def cell(code, advance, img):
    """One glyph cell image cropped to its ink: (code, advance, x, y, w, h, coverage 0..15 row by row)."""
    x0, y0, x1, y1 = img.getbbox() or (0, 0, 0, 0)
    px = [(img.getpixel((x, y)) * 15 + 127) // 255 for y in range(y0, y1) for x in range(x0, x1)]
    return (code, advance, x0, y0, x1 - x0, y1 - y0, px)


def font_dir():
    if 'DEJAVU' in os.environ:
        return Path(os.environ['DEJAVU'])
    import matplotlib
    return Path(matplotlib.get_data_path()) / 'fonts' / 'ttf'


def glyphs(path, size):
    """Yields (char code, advance, x, y, w, h, coverage 0..15 row by row) for FIRST..LAST, and the line height."""
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    out = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = round(font.getlength(ch))
        img = Image.new('L', (advance, height), 0)
        # ponytail: ink left of the origin or right of the advance (j, f in some fonts) is cut, so each glyph
        # stays in its own cell and never overwrites its neighbours; a real kerning model if it ever shows.
        ImageDraw.Draw(img).text((0, ascent), ch, font=font, fill=255, anchor='ls')
        out.append(cell(code, advance, img))
    return height, ascent, out


def main():
    d = font_dir()
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    lines = ['//! Generated by tools/font.py: do not edit. PIXEL is this project\'s own; the others are rasterized from',
             '//! DejaVu Sans.',
             '//!',
             '//! DejaVu fonts: Bitstream Vera Fonts Copyright (c) 2003 Bitstream, Inc.; DejaVu changes are in the',
             '//! public domain. The Bitstream Vera licence allows modified copies (these bitmaps) as long as they are',
             '//! not sold on their own and are not named "Bitstream" or "Vera".',
             '',
             'use crate::text::{Font, Glyph};',
             '']
    total = 0
    for name, file, size, what in FONTS:
        height, ascent, gs = pixel_glyphs() if file == 'pixel' else glyphs(d / file, size)
        data, table = bytearray(), []
        for code, advance, x, y, w, h, px in gs:
            at = len(data)
            px = px + [0] * (len(px) % 2)
            data += bytes(px[i] << 4 | px[i + 1] for i in range(0, len(px), 2))
            glyph = f'Glyph {{ advance: {advance}, x: {x}, y: {y}, w: {w}, h: {h}, at: {at} }}'
            table.append(f'    {glyph}, // {chr(code)!r}')
        total += len(data) + 8 * len(gs)
        source = 'Pixel font (tools/pixel_font.py)' if file == 'pixel' else f'{file[:-4]} {size} px'
        lines += [f'/// {source}, for {what}: {height} px per line, baseline {ascent} px from the top.',
                  f'pub static {name}: Font =',
                  f'    Font {{ height: {height}, glyphs: &{name}_GLYPHS, alpha: &{name}_ALPHA }};',
                  '',
                  f'static {name}_GLYPHS: [Glyph; {len(gs)}] = [',
                  *table,
                  '];',
                  '',
                  f'static {name}_ALPHA: [u8; {len(data)}] = [']
        for i in range(0, len(data), 24):
            lines.append('    ' + ' '.join(f'0x{b:02x},' for b in data[i:i + 24]))
        lines += ['];', '']
    out = ROOT / 'src' / 'fonts.rs'
    out.write_text('\n'.join(lines))
    subprocess.run(['rustfmt', '--edition', '2024', '--config-path', str(ROOT / 'rustfmt.toml'), str(out)], check=True)
    print(f'src/fonts.rs: {len(FONTS)} fonts, about {total} B in the image')


if __name__ == '__main__':
    sys.exit(main())
