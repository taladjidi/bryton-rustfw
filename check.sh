#!/bin/sh
# Everything to pass before a commit: format, lints, host tests (+ target/sim/*.bmp), firmware build, packing,
# the offline checks of tools/dev.py.
set -e
cd "$(dirname "$0")"
skipped=""  # the checks left out (named at the end)
# The split (AGENTS.md, Layout): the library cannot reach hardware, since it forbids unsafe; unsafe lives in hw.rs,
# plus usb.rs's one marker-trait line.
grep -q '^#!\[forbid(unsafe_code)\]' src/lib.rs || { echo "layout: src/lib.rs lost #![forbid(unsafe_code)]"; exit 1; }
n=$(grep -rl 'allow(unsafe_code)\|unsafe {\|unsafe fn\|unsafe impl' src | sort | grep -v '^src/board/hw.rs$' | tr '\n' ' ')
[ "$n" = "src/board/usb.rs " ] && [ "$(grep -c 'unsafe impl\|allow(unsafe_code)' src/board/usb.rs)" = 2 ] \
    || { echo "layout: unsafe outside hw.rs: $n"; exit 1; }
# The merge guard: no conflict marker left in a tracked text file (one reached main on 2026-10-29 through a
# branch's own merge of main, and nothing else here reads the docs).
m=$(git ls-files -z -- '*.rs' '*.md' '*.py' '*.sh' '*.toml' '*.x' | xargs -0 grep -l '^<<<<<<< \|^>>>>>>> ' 2>/dev/null | tr '\n' ' ')
[ -z "$m" ] || { echo "merge: conflict markers in: $m"; exit 1; }
# The docs guard: every file of src and tools is named in docs/layout.md, by its path or by its basename as a
# backticked word (`menus.rs`); the data folders (tools/fonts/) are the only ones without an entry of their own.
# No doc names the files that moved (src/sim.rs, src/ui.rs).
miss=""
for f in $(git ls-files -co --exclude-standard src tools); do
    ok=0
    grep -qF "$f" docs/layout.md && ok=1
    grep -qF "\`$(basename "$f")\`" docs/layout.md && ok=1
    [ "$ok" = 1 ] && continue
    case $f in tools/fonts/*) continue ;; esac
    miss="$miss $f"
done
[ -z "$miss" ] || { echo "docs: not in docs/layout.md:$miss"; exit 1; }
if git grep -nE '(^|[^A-Za-z0-9_])(src/)?(sim|ui)\.rs' -- '*.md'; then echo "docs: a doc names src/sim.rs or src/ui.rs (src/sim/, src/ui/)"; exit 1; fi
# tools/lint.py: pub items only tests use, dashes, licensed keys in tracked files, dead tool functions, ruff (pyflakes)
lint_out=$(python3 -I tools/lint.py) || { echo "$lint_out"; exit 1; }
echo "$lint_out"
case $lint_out in *"keys: no key files"*) skipped="${skipped:+$skipped }keys" ;; esac
python3 -I tools/lint.py selftest
command -v ruff >/dev/null 2>&1 || skipped="${skipped:+$skipped }ruff"
cargo fmt --check
cargo clippy --release -- -D warnings
cargo clippy --tests --target aarch64-apple-darwin -q -- -D warnings  # the tests and the simulator too
cargo test-host
RUSTDOCFLAGS="-D warnings" cargo doc --target aarch64-apple-darwin --no-deps -q  # docs: no broken or private links
if command -v cargo-deny >/dev/null 2>&1; then cargo deny check -s; else echo "cargo-deny: not installed, skipped"; skipped="${skipped:+$skipped }cargo-deny"; fi
cargo build --release
python3 -I tools/stack_check.py
python3 -I tools/stack_check.py selftest
python3 -I tools/pack.py
# src/ui/fonts.rs is generated by tools/font.py (AGENTS.md, Layout): regenerate it into a temporary file and compare;
# skipped without PIL. Plain python3, not -I: -I drops the user site-packages, where PIL may be (font.py reads only
# this repository's files).
if python3 -c 'import PIL' 2>/dev/null; then
    fontdir="$(mktemp -d)"; trap 'rm -rf "$fontdir"' EXIT
    python3 tools/font.py -o "$fontdir/fonts.rs" >/dev/null
    cmp -s "$fontdir/fonts.rs" src/ui/fonts.rs || { echo "src/ui/fonts.rs differs from tools/font.py's output: run python3 tools/font.py"; exit 1; }
else
    skipped="${skipped:+$skipped }font (PIL)"
fi
# the live numbers of the docs (markers, AGENTS.md Docs): after the tests and tools/pack.py, so the ELF and the test list
# exist; --write prints each marker it changed
python3 -I tools/numbers.py --write
python3 -I tools/numbers.py selftest
python3 -I tools/dev.py selftest
python3 -I tools/sync.py selftest  # a fake Intervals.icu and Strava on 127.0.0.1: no network
python3 -I tools/assist.py selftest  # AssistNow Offline trim and copy; no network
python3 -I tools/segments.py selftest  # the live segment writer on synthetic efforts; the committed fixture equals a fresh one
python3 -I tools/s810_probe.py selftest  # the S810 owner's probe on a made-up volume: nothing personal comes out
python3 -I tools/route_pack.py selftest  # the synthetic map file (test-data/route) built and read back by an independent reader
python3 -I tools/ign_pack.py selftest
python3 -I tools/map_pack.py selftest  # the OpenStreetMap packs from a synthetic Overpass JSON, read back by an independent reader
python3 -I tools/theme.py selftest  # the example theme files: the committed fixture equals a fresh build (ui/theme.rs parses it)
# the test rides decoded by independent readers (fitdecode, Garmin's FIT SDK): FIT_PYTHON may name a Python that has
# them (a venv); skipped when neither has them
PY="${FIT_PYTHON:-python3}"
if "$PY" -c 'import fitdecode, garmin_fit_sdk' 2>/dev/null; then
    "$PY" tools/fit_check.py target/fit/sample.fit target/fit/cut.fit target/fit/sample_full.fit
    "$PY" tools/fit_check.py --pair target/fit/recorded.fit target/fit/recorded_full.fit
    "$PY" tools/fit_check.py --profile target/fit/indoor.fit target/fit/older.fit target/fit/mtb.fit
else
    echo "fit_check: fitdecode / garmin-fit-sdk not installed, skipped (FIT_PYTHON)"
    skipped="${skipped:+$skipped }fit_check"
fi
# The firmware on Renode's STM32H747 (renode/run.py), when Renode is installed (docs/devloop.md, Emulation).
export RENODE="${RENODE:-/Applications/Renode.app/Contents/MacOS/renode}"
if command -v "$RENODE" >/dev/null 2>&1; then
    python3 renode/run.py
    python3 renode/run.py --vbus
    python3 renode/run.py --off
else
    echo "renode: not found, emulator checks skipped (docs/devloop.md, Emulation)"
    skipped="${skipped:+$skipped }renode"
fi
if [ -n "$skipped" ]; then echo "SKIPPED: $skipped"; fi
